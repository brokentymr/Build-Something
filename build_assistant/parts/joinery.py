def tool_schedule(operations: set[str]) -> tuple[ToolEntry, ...]:
    """Derive the tool schedule from the set of operations present.

    Never authored directly. Every entry traces to an operation in ``operations``.
    """
    out: list[ToolEntry] = []
    seen: set[tuple[str, str]] = set()
    for op in sorted(operations):
        if op not in _OPERATION_TOOLS:
            raise KeyError(f"operation {op!r} has no tool mapping (Part 3: no unjustified tools)")
        for te in _OPERATION_TOOLS[op]:
            key = (te.tool, te.setting)
            if key not in seen:
                seen.add(key)
                out.append(te)
    return tuple(out)


def fastener_bom(joints: tuple[Joint, ...]) -> dict[str, dict]:
    """Aggregate a derived fastener bill by fastener id."""
    bom: dict[str, dict] = {}
    for j in joints:
        f = get_fastener(j.fastener_id)
        rec = bom.setdefault(
            j.fastener_id,
            {"fastener": f, "count": 0, "pilot": f.pilot_diameter,
             "countersink": f.countersink_diameter, "driver": f.driver_bit},
        )
        rec["count"] += j.count()
    return bom
