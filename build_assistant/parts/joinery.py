"""Joinery templates — Phase 2, brief Part 3.

Part sizes are a function of ``(dimensions, allowances, joinery_template)`` — never
of dimensions alone. A template also carries a *fastener schedule* and *implied
operations*; the tool schedule is **derived from the operation list**, not
authored (Part 3). If a tool appears without an operation that requires it, that
is a bug.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Callable

from ..catalog.fasteners import get_fastener


@dataclass(frozen=True)
class Joint:
    """One fastened seam. Fastener count is derived from length and spacing."""

    name: str
    fastener_id: str
    seam_length: float        # linear inches of the seam
    spacing: float            # inches between fasteners
    rows: int = 1             # parallel rows of fasteners
    operation: str = ""       # the operation that implies tools

    def count(self) -> int:
        per_row = max(2, int(self.seam_length // self.spacing) + 1)
        return per_row * self.rows


@dataclass(frozen=True)
class ToolEntry:
    tool: str
    setting: str
    justified_by: str         # the operation that requires it — never empty


@dataclass(frozen=True)
class JoineryTemplate:
    id: str
    applies_to: tuple[str, ...]
    is_default: bool
    description: str


